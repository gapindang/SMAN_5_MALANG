import {mkdir,writeFile} from 'node:fs/promises';

// Pinned upstream SVGs; the generated sprite is committed and served locally.
const version='0.468.0';
const names=['arrow-up-right','arrow-right','arrow-left','arrow-up','arrow-down','chevron-left','chevron-right','plus','minus','x','menu','refresh-cw','sparkles','leaf','map-pin','mail','phone','clock','search','book-open','download','zoom-in','zoom-out','maximize-2','share-2','log-in','log-out','eye','eye-off','newspaper','images','settings','pencil','trash-2','save','send','bold','italic','heading-2','heading-3','pilcrow','list','list-ordered','quote','link','image-plus','check','lock-keyhole'];
async function download(path){const response=await fetch(`https://unpkg.com/lucide-static@${version}/${path}`);if(!response.ok)throw Error(`Download ${path}: ${response.status}`);return response.text();}
const symbols=[];
for(const name of names){
 const svg=await download(`icons/${name}.svg`);
 const body=svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1];
 if(!body)throw Error(`Invalid SVG: ${name}`);
 symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${body.trim()}</symbol>`);
}
await mkdir('public/icons',{recursive:true});
await writeFile('public/icons/lucide.svg',`<!-- Lucide ${version}; see lucide-LICENSE.txt. Generated by scripts/sync-icons.mjs. -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`);
await writeFile('public/icons/lucide-LICENSE.txt',await download('LICENSE'));
await writeFile('src/lib/icons.ts',`// Names included in public/icons/lucide.svg. Generated by scripts/sync-icons.mjs.\nexport type IconName = ${names.map(name=>`'${name}'`).join(' | ')};\n`);
console.log(`Saved ${names.length} Lucide icons (${version}).`);
